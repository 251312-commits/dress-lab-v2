/* Dress Lab V2 — non-destructive skin tone recoloring.
 *
 * Source sprites remain immutable. Skin pixels are identified from the original
 * pink undertone and adjusted relative to the original unshaded #FAEDED.
 * Transparent edges, line art, other colors, original shadows and body-shape
 * source images remain intact. Tinted canvases are cached by source image
 * identity until either the color or the deformed sprite changes.
 */
(() => {
  "use strict";

  const BASE_HEX = "#FAEDED";
  const BASE = Object.freeze([250, 237, 237]);
  const clamp = (value, min, max) => Math.max(min, Math.min(max, value));
  const HEX = /^#[0-9a-f]{6}$/i;

  function hexToRgb(hex) {
    if (typeof hex !== "string" || !HEX.test(hex)) return null;
    return [1, 3, 5].map(index => parseInt(hex.slice(index, index + 2), 16));
  }

  // Reduce accidental edits to whites, charcoal outlines and other details.
  // Neutral gray and white have no pink undertone; skin and its shadows do.
  // A soft boundary avoids color discontinuities in anti-aliased edges.
  function skinWeight(red, green, blue) {
    const warmth = Math.min(red - green, red - blue);
    if (warmth <= 2) return 0;
    const neutrality = Math.abs(green - blue);
    const undertone = clamp((warmth - 2) / 7, 0, 1);
    const balance = clamp((30 - neutrality) / 16, 0, 1);
    const shadows = clamp((red - 25) / 30, 0, 1);
    return undertone * balance * shadows;
  }

  function recolorPixels(pixels, target) {
    const ratioR = target[0] / BASE[0];
    const ratioG = target[1] / BASE[1];
    const ratioB = target[2] / BASE[2];
    for (let i = 0; i < pixels.length; i += 4) {
      if (!pixels[i + 3]) continue;
      const red = pixels[i], green = pixels[i + 1], blue = pixels[i + 2];
      const weight = skinWeight(red, green, blue);
      if (!weight) continue;
      pixels[i] = clamp(Math.round(red * (1 + weight * (ratioR - 1))), 0, 255);
      pixels[i + 1] = clamp(Math.round(green * (1 + weight * (ratioG - 1))), 0, 255);
      pixels[i + 2] = clamp(Math.round(blue * (1 + weight * (ratioB - 1))), 0, 255);
      // Keep alpha completely unchanged.
    }
    return pixels;
  }

  class DressLabSkinTone {
    constructor(rig) {
      if (!rig || typeof rig.render !== "function") {
        throw new Error("DressLabSkinTone requires a working character rig");
      }
      this.rig = rig;
      this.hex = BASE_HEX;
      this.target = BASE.slice();
      this.cache = new WeakMap();
      this.pending = null;
      this.frame = 0;
      rig.skinTone = this;
    }

    getColor() { return this.hex; }

    // Paint at most once per animation frame while dragging the color wheel.
    queueColor(hex) {
      if (!hexToRgb(hex)) return false;
      this.pending = hex.toUpperCase();
      if (!this.frame) {
        this.frame = requestAnimationFrame(() => {
          this.frame = 0;
          const next = this.pending;
          this.pending = null;
          if (next) this.setColor(next);
        });
      }
      return true;
    }

    setColor(hex) {
      const rgb = hexToRgb(hex);
      if (!rgb) return false;
      const normalized = hex.toUpperCase();
      if (this.hex === normalized) return true;
      this.hex = normalized;
      this.target = rgb;
      this.cache = new WeakMap();
      this.rig.render();
      return true;
    }

    // The unmodified native sprites are used for exactly #FAEDED.
    getImage(image) {
      if (!image || this.hex === BASE_HEX) return image;
      const cached = this.cache.get(image);
      if (cached) return cached;
      const width = image.naturalWidth || image.width;
      const height = image.naturalHeight || image.height;
      if (!width || !height) return image;
      const canvas = document.createElement("canvas");
      canvas.width = width;
      canvas.height = height;
      const context = canvas.getContext("2d", { willReadFrequently: true });
      if (!context) return image;
      context.drawImage(image, 0, 0);
      const pixels = context.getImageData(0, 0, width, height);
      recolorPixels(pixels.data, this.target);
      context.putImageData(pixels, 0, 0);
      this.cache.set(image, canvas);
      return canvas;
    }

    // Joint-cap circles are generated by the rig, not PNG sprites.
    // Tint only their fill; leave the fine outline as originally drawn.
    getJointCapFill() {
      if (this.hex === BASE_HEX) return "#F7E4E5";
      const original = [247, 228, 229];
      const color = original.map((v, i) => clamp(
        Math.round(v * this.target[i] / BASE[i]), 0, 255
      ));
      return "#" + color.map(v => v.toString(16).padStart(2, "0")).join("").toUpperCase();
    }

    destroy() {
      if (this.frame) cancelAnimationFrame(this.frame);
      this.frame = 0;
      this.pending = null;
      if (this.rig.skinTone === this) this.rig.skinTone = null;
      this.cache = new WeakMap();
    }
  }

  // Export the pure pixel transform for regression tests without a DOM.
  window.DressLabSkinTone = DressLabSkinTone;
  window.DressLabSkinToneUtils = { skinWeight, recolorPixels, hexToRgb, BASE_HEX };
})();
